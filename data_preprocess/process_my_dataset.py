"""
数据处理脚本，用于将用户自己的CSV数据集转换为时间序列预测框架所需的格式。

功能:
1. 读取一个包含多个时间序列的CSV文件。
2. 根据指定的ID列，将数据拆分为每个ID一个的Parquet文件。
3. 创建一个数据配置文件(YAML)，用于框架加载数据。
4. 生成一个元数据文件(id_info.json)的模板，供用户填充。

使用示例:
假设你有一个名为 `my_data.csv` 的文件，内容如下:
station_id,timestamp,temperature
A,2022-01-01 00:00:00,10.5
B,2022-01-01 00:00:00,15.2
A,2022-01-01 01:00:00,10.8
B,2022-01-01 01:00:00,14.9
...

你可以运行以下命令来处理它:
python process_my_dataset.py \
    --input-csv /path/to/my_data.csv \
    --output-dir my_processed_data \
    --id-col station_id \
    --timestamp-col timestamp \
    --target-col temperature \
    --split-dates 2022-09-01 2022-11-01
"""

import os
import pandas as pd
import json
import argparse
from tqdm import tqdm

def process_csv_to_parquet(input_csv, output_dir, id_col, timestamp_col, target_col, timestamp_format):
    """
    读取CSV文件，按ID拆分，并保存为Parquet格式。

    Args:
        input_csv (str): 输入的CSV文件路径。
        output_dir (str): 输出目录，用于存放处理后的文件。
        id_col (str): CSV中用作唯一标识符的列名。
        timestamp_col (str): CSV中时间戳的列名。
        target_col (str): CSV中要预测的目标值的列名。
        timestamp_format (str, optional): 时间戳的格式，用于pandas解析。

    Returns:
        list: 数据集中所有唯一的ID列表。
    """
    print(f"--- Step 1: Processing CSV file: {input_csv} ---")

    # 1. 创建输出目录
    os.makedirs(output_dir, exist_ok=True)

    # 2. 读取并预处理CSV
    print("Reading CSV file into memory...")
    try:
        df = pd.read_csv(input_csv)
    except FileNotFoundError:
        print(f"Error: Input file not found at {input_csv}")
        exit()

    # 检查必要的列是否存在
    required_cols = [id_col, timestamp_col, target_col]
    if not all(col in df.columns for col in required_cols):
        print(f"Error: CSV file must contain the following columns: {required_cols}")
        print(f"Found columns: {list(df.columns)}")
        exit()

    print("Converting timestamp column...")
    try:
        # 将时间戳列转换为datetime对象，这是框架处理的基础
        df[timestamp_col] = pd.to_datetime(df[timestamp_col], format=timestamp_format)
    except Exception as e:
        print(f"Error parsing timestamp column '{timestamp_col}'.")
        print("Please check if your --timestamp-format matches the data.")
        print(f"Pandas error: {e}")
        exit()

    # 3. 获取所有唯一的ID
    unique_ids = df[id_col].unique()
    print(f"Found {len(unique_ids)} unique IDs. Processing each one...")

    # 4. 按ID拆分并保存为Parquet
    for station_id in tqdm(unique_ids, desc="Processing IDs"):
        # 筛选出当前ID的数据
        id_df = df[df[id_col] == station_id].copy()

        # 为了与框架兼容，重命名列
        # 框架期望时间戳列名为'date'，目标列名为'value'（或在config中指定的名称）
        id_df.rename(columns={
            timestamp_col: 'date',
            target_col: 'value'  # 我们统一使用 'value' 作为内部目标名称
        }, inplace=True)

        # 确保数据按时间排序
        id_df.sort_values('date', inplace=True)
        
        # 选择需要的列
        output_df = id_df[['date', 'value']]

        # 保存为Parquet文件
        file_path = os.path.join(output_dir, f'id_{station_id}.parquet')
        output_df.to_parquet(file_path)

    print(f"\nSuccessfully processed and saved {len(unique_ids)} time series to: {output_dir}")

    # 5. 生成一个id_info.json的模板
    id_info = {}
    for station_id in unique_ids:
        id_info[str(station_id)] = {
            'description': f'Description for station {station_id}. PLEASE EDIT THIS.',
            'sensor_downtime': {} # 如果有已知的停机时间，可以手动添加
        }
    
    id_info_path = os.path.join(output_dir, 'id_info.json')
    with open(id_info_path, 'w') as f:
        json.dump(id_info, f, indent=2)
    print(f"Generated metadata template at: {id_info_path}")
    print("ACTION REQUIRED: Please open this file and add meaningful descriptions.")
    
    return unique_ids

def create_data_config(data_dir, split_dates, sampling_rate, config_name):
    """
    创建数据配置文件 (YAML)。

    Args:
        data_dir (str): 包含处理后数据的目录。
        split_dates (list): 用于划分训练/验证/测试集的日期字符串列表。
        sampling_rate (str): 数据的采样频率 (e.g., '1h', '15min', '1d')。
        config_name (str): 输出的YAML配置文件名。
    """
    print(f"\n--- Step 2: Creating data configuration file ---")
    
    # 格式化分割日期
    split_info_str = "\n".join([f"  - '{date}'" for date in split_dates])

    # YAML配置内容
    config_content = f"""# Dataset configuration for: {config_name}
# Auto-generated by process_my_dataset.py

root_path: {data_dir}
spliter: timestamp
split_info:
{split_info_str}

timestamp_col: date
target: 
  - value
id_info: id_info.json
id: all
formatter: 'id_{{{{i}}}}.parquet'
sampling_rate: {sampling_rate} # IMPORTANT: Please verify this is correct for your data!
"""
    
    # 创建目录并写入文件
    os.makedirs('data_configs', exist_ok=True)
    config_path = os.path.join('data_configs', f'{config_name}.yaml')
    
    with open(config_path, 'w') as f:
        f.write(config_content)
    
    print(f"Created data configuration at: {config_path}")
    return config_path

def main():
    """主函数，解析参数并执行处理流程。"""
    parser = argparse.ArgumentParser(description="Process a custom CSV dataset for the time series framework.")
    parser.add_argument('--input-csv', required=True, help="Path to your input CSV file.")
    parser.add_argument('--output-dir', required=True, help="Directory to save the processed files (Parquet, JSON).")
    parser.add_argument('--id-col', required=True, help="Column name in the CSV that identifies each time series.")
    parser.add_argument('--timestamp-col', required=True, help="Column name for the timestamp.")
    parser.add_argument('--target-col', required=True, help="Column name for the target value to be forecasted.")
    parser.add_argument('--split-dates', nargs='+', required=True, help="Two dates for splitting data into train/val/test. E.g., '2022-09-01' '2022-11-01'.")
    parser.add_argument('--sampling-rate', default='1h', help="Sampling rate of the data (e.g., '1h', '1d', '15min'). Default: '1h'.")
    parser.add_argument('--timestamp-format', default=None, help="The format of your timestamp string (e.g., '%%Y-%%m-%%d %%H:%%M:%%S'). If not provided, pandas will try to infer it.")
    
    args = parser.parse_args()

    if len(args.split_dates) != 2:
        print("Error: --split-dates requires exactly two dates.")
        exit()

    # Step 1: 处理CSV并生成Parquet文件
    process_csv_to_parquet(
        input_csv=args.input_csv,
        output_dir=args.output_dir,
        id_col=args.id_col,
        timestamp_col=args.timestamp_col,
        target_col=args.target_col,
        timestamp_format=args.timestamp_format
    )

    # Step 2: 创建数据配置文件
    config_name = os.path.splitext(os.path.basename(args.input_csv))[0]
    config_path = create_data_config(
        data_dir=args.output_dir,
        split_dates=args.split_dates,
        sampling_rate=args.sampling_rate,
        config_name=config_name
    )

    # Step 3: 显示如何使用
    print("\n--- Step 3: How to Use Your New Dataset ---")
    print("\n✅ Your dataset is now ready to be used with the framework!")
    print(f"\nTo train a model (e.g., DLinear) with your data, run a command like this:")
    print("="*80)
    print(f"python run.py --model DLinear --data_config {config_path} --model_config model_configs/general/DLinear.yaml --input_len 96 --output_len 24")
    print("="*80)
    print("\nNOTE: Adjust --input_len and --output_len based on your needs and data frequency.")
    print("If you have heterogeneous data (like weather), you will need to add the 'hetero_info' block to your YAML file manually, following the original example's structure.")

if __name__ == "__main__":
    main()